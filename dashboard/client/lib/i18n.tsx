type Vars = Record<string, string | number>;
function fill(s: string, vars?: Vars) {
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`)) : s;
}

interface I18nCtx { lang: Lang; setLang: (l: Lang) => void; t: (key: string, vars?: Vars) => string; }
const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const saved = (typeof window !== "undefined" && localStorage.getItem("sentinel_lang")) as Lang | null;
    if (saved && saved in T) setLangState(saved);
  }, []);
  const setLang = (l: Lang) => { setLangState(l); if (typeof window !== "undefined") localStorage.setItem("sentinel_lang", l); };
  const t = (key: string, vars?: Vars) => fill(T[lang][key] ?? T.en[key] ?? key, vars);
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useT() {
  const c = useContext(Ctx);
  if (!c) return { lang: "en" as Lang, setLang: () => {}, t: (k: string, vars?: Vars) => fill(T.en[k] ?? k, vars) };
  return c;
}
